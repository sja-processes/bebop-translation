def _parse(block):
    rows = [r for r in block.strip('\n').split('\n')]
    glyphs = []
    for i in range(0, len(rows), 9):
        band = [r.split() for r in rows[i:i + 8]]
        for g in range(len(band[0])):
            glyphs.append([band[y][g] for y in range(8)])
    return glyphs


def build():
    """-> {char: (tile, [8 row strings])}"""
    out = {}
    for chars, block, base in ((
            'ABCDEFGHIJKLMNOPQRSTUVWXYZ', UPPER, 0x00),
            ('abcdefghijklmnopqrstuvwxyz', LOWER, 0x1A),
            (PUNCT_CHARS, PUNCT, 0x34),
            ('0123456789', DIGITS, 0x42)):
        glyphs = _parse(block)
        assert len(glyphs) == len(chars), (chars, len(glyphs))
        for i, ch in enumerate(chars):
            out[ch] = (base + i, glyphs[i])
    return out


def tile_bytes(rows):
    """8 row strings -> 16 CHR bytes: ink colour 0, background colour 1."""
    lo = bytes(sum((0 if r[x] == '#' else 1) << (7 - x) for x in range(8))
               for r in (row.ljust(8, '.') for row in rows))
    return lo + bytes(8)


# Characters that keep existing game tiles.
KEEP = {'♥': 0x59, ' ': 0xFE}


def char_map():
    m = {ch: t for ch, (t, _) in build().items()}
    m.update(KEEP)
    return m
